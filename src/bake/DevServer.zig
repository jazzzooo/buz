// For debugging, it is helpful to be able to see bundles.
pub fn dumpBundle(io: std.Io, dump_dir: std.Io.Dir, graph: bake.Graph, rel_path: []const u8, chunk: []const u8, wrap: bool) !void {
    const buf = bun.path_buffer_pool.get();
    defer bun.path_buffer_pool.put(buf);
    const name = bun.path.joinAbsStringBuf("/", buf, &.{
        @tagName(graph),
        rel_path,
    }, .auto)[1..];
    var inner_dir = try bun.MakePath.makeOpenPath(io, dump_dir, std.fs.path.dirname(name).?, .{});
    defer inner_dir.close(io);

    const file = try inner_dir.createFile(io, std.fs.path.basename(name), .{});
    defer file.close(io);
    var file_buffer: [1024]u8 = undefined;
    var file_writer = file.writerStreaming(io, &file_buffer);
    const bufw = &file_writer.interface;

    if (!bun.strings.hasSuffixComptime(rel_path, ".map")) {
        try bufw.print("// {f} bundled for {s}\n", .{
            bun.fmt.quote(rel_path),
            @tagName(graph),
        });
        try bufw.print("// Bundled at {d}, Bun " ++ bun.Global.package_json_version_with_canary ++ "\n", .{
            bun.timespec.realNow().nsSigned(),
        });
    }

    // Wrap in an object to make it valid syntax. Regardless, these files
    // are never executable on their own as they contain only a single module.

    if (wrap)
        try bufw.writeAll("({\n");

    try bufw.writeAll(chunk);

    if (wrap)
        try bufw.writeAll("});\n");

    try bufw.flush();
}

pub noinline fn dumpBundleForChunk(dev: *DevServer, dump_dir: std.Io.Dir, side: bake.Side, key: []const u8, code: []const u8, wrap: bool, is_ssr_graph: bool) void {
    const cwd = dev.root;
    const rel_path = bun.handleOom(std.fs.path.relative(bun.default_allocator, cwd, null, cwd, key));
    defer bun.default_allocator.free(rel_path);
    const rel_path_escaped = bun.handleOom(std.mem.replaceOwned(u8, bun.default_allocator, rel_path, ".." ++ std.fs.path.sep_str, "_.._" ++ std.fs.path.sep_str));
    defer bun.default_allocator.free(rel_path_escaped);
    dumpBundle(dev.vm.io, dump_dir, switch (side) {
        .client => .client,
        .server => if (is_ssr_graph) .ssr else .server,
    }, rel_path_escaped, code, wrap) catch |err| {
        bun.handleErrorReturnTrace(err, @errorReturnTrace());
        Output.warn("Could not dump bundle: {}", .{err});
    };
}

