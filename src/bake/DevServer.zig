const DeferredPromise = struct {
    completion: RouteBundlePromise = .empty,
    route_bundle_indices: std.array_hash_map.Auto(RouteBundle.Index, void) = .empty,

    pub fn setRouteBundleState(self: *DeferredPromise, dev: *DevServer, state: RouteBundle.State) void {
        for (self.route_bundle_indices.keys()) |route_bundle_index| {
            dev.routeBundlePtr(route_bundle_index).server_state = state;
        }
    }

    pub fn reset(self: *DeferredPromise) void {
        self.completion.deinit();
        self.route_bundle_indices.clearRetainingCapacity();
    }

    pub fn take(self: *DeferredPromise) DeferredPromise {
        const result = DeferredPromise{
            .completion = self.completion.take(),
            .route_bundle_indices = self.route_bundle_indices,
        };
        self.route_bundle_indices = .empty;
        return result;
    }

    pub fn deinitIdempotently(self: *DeferredPromise) void {
        self.completion.deinit();
        self.route_bundle_indices.deinit(bun.default_allocator);
        self.route_bundle_indices = .{};
    }
};

/// DevServer is stored on the heap, storing its allocator.
pub fn init(options: Options) bun.JSOOM!*DevServer {
    bun.analytics.Features.dev_server +|= 1;

    var dump_dir = if (bun.FeatureFlags.bake_debugging_features)
        if (options.dump_sources) |dir|
            bun.MakePath.makeOpenPath(options.vm.io, std.Io.Dir.cwd(), dir, .{}) catch |err| dir: {
                bun.handleErrorReturnTrace(err, @errorReturnTrace());
                Output.warn("Could not open directory for dumping sources: {}", .{err});
                break :dir null;
            }
        else
            null;
    errdefer if (bun.FeatureFlags.bake_debugging_features) if (dump_dir) |*dir| dir.close(options.vm.io);

    const separate_ssr_graph = if (options.framework.server_components) |sc| sc.separate_ssr_graph else false;

    const dev = bun.new(DevServer, .{
        .allocation_scope = .initDefault(options.vm.io),
        .root = options.root,
        .vm = options.vm,
        .server = null,
        .directory_watchers = .empty,
        .server_fetch_function_callback = null,
        .server_register_update_callback = null,
        .ensure_async_local_storage_callback = null,
        .bundle_new_route_callback = null,
        .new_route_params_callback = null,
        .generation = 0,
        .graph_safety_lock = .initUnlocked(),
        .dump_dir = dump_dir,
        .framework = options.framework,
        .route_styles = options.route_styles,
        .bundler_options = options.bundler_options,
        .emit_incremental_visualizer_events = 0,
        .emit_memory_visualizer_events = 0,
        .memory_visualizer_timer = .initPaused(.DevServerMemoryVisualizerTick),
        .has_pre_crash_handler = bun.FeatureFlags.bake_debugging_features and bun.feature_flag.BUN_DUMP_STATE_ON_CRASH.get(),
        .frontend_only = options.framework.file_system_router_types.len == 0,
        .client_graph = .empty,
        .server_graph = .empty,
        .incremental_result = .empty,
        .route_lookup = .empty,
        .route_bundles = .empty,
        .html_router = .empty,
        .active_websocket_connections = .empty,
        .current_bundle = null,
        .next_bundle = .{
            .route_queue = .empty,
            .reload_event = null,
            .requests = .{},
            .promise = .{},
        },
        .inspector_server_id = .init(0), // TODO paper clover:
        .assets = .{
            .path_map = .empty,
            .files = .empty,
            .refs = .empty,
        },
        .source_maps = .empty,
        .plugin_state = .unknown,
        .bundling_failures = .{},
        .assume_perfect_incremental_bundling = bun.feature_flag.BUN_ASSUME_PERFECT_INCREMENTAL.get() orelse bun.Environment.isDebug,
        .testing_batch_events = .disabled,
        .broadcast_console_log_from_browser_to_server = options.broadcast_console_log_from_browser_to_server,
        .server_transpiler = undefined,
        .client_transpiler = undefined,
        .ssr_transpiler = undefined,
        .bun_watcher = undefined,
        .configuration_hash_key = undefined,
        .router = undefined,
        .watcher_atomics = undefined,
        .hot_reload_task = undefined,
        .log = undefined,
        .deferred_request_pool = undefined,
    });
    errdefer bun.destroy(dev);
    const alloc = dev.allocator();
    dev.log = .init(alloc);
    dev.deferred_request_pool = .init(alloc);

    const global = dev.vm.global;

    assert(dev.server_graph.owner() == dev);
    assert(dev.client_graph.owner() == dev);
    assert(dev.directory_watchers.owner() == dev);

    dev.graph_safety_lock.lock();
    defer dev.graph_safety_lock.unlock();

    const generic_action = "while initializing development server";
    const fs = bun.fs.FileSystem.init(dev.vm.io, options.root) catch |err|
        return global.throwError(err, generic_action);

    dev.bun_watcher = Watcher.init(DevServer, dev, fs, bun.default_allocator) catch |err|
        return global.throwError(err, "while initializing file watcher for development server");

    errdefer dev.bun_watcher.deinit(false);
    dev.bun_watcher.start() catch |err|
        return global.throwError(err, "while initializing file watcher thread for development server");

    dev.watcher_atomics = WatcherAtomics.init(dev);

    // This causes a memory leak, but the allocator is otherwise used on multiple threads.
    const transpiler_allocator = bun.default_allocator;

    bake.FrameworkTranspilerEngine.init(&dev.framework, transpiler_allocator, dev.vm.io, &dev.log, .development, .server, &dev.server_transpiler, &dev.bundler_options.server) catch |err|
        return global.throwError(err, generic_action);
    dev.server_transpiler.options.dev_server = dev;
    bake.FrameworkTranspilerEngine.init(
        &dev.framework,
        transpiler_allocator,
        dev.vm.io,
        &dev.log,
        .development,
        .client,
        &dev.client_transpiler,
        &dev.bundler_options.client,
    ) catch |err|
        return global.throwError(err, generic_action);
    dev.client_transpiler.options.dev_server = dev;

    dev.server_transpiler.resolver.watcher = dev.bun_watcher.getResolveWatcher();
    dev.client_transpiler.resolver.watcher = dev.bun_watcher.getResolveWatcher();

    if (separate_ssr_graph) {
        bake.FrameworkTranspilerEngine.init(&dev.framework, transpiler_allocator, dev.vm.io, &dev.log, .development, .ssr, &dev.ssr_transpiler, &dev.bundler_options.ssr) catch |err|
            return global.throwError(err, generic_action);
        dev.ssr_transpiler.options.dev_server = dev;
        dev.ssr_transpiler.resolver.watcher = dev.bun_watcher.getResolveWatcher();
    }

    assert(dev.server_transpiler.resolver.opts.target != .browser);
    assert(dev.client_transpiler.resolver.opts.target == .browser);

    dev.framework = dev.framework.resolve(&dev.server_transpiler.resolver, &dev.client_transpiler.resolver, options.arena) catch {
        if (dev.framework.is_built_in_react)
            try bake.Framework.addReactInstallCommandNote(&dev.log);
        return LoggerEngine.throwAggregateError(&dev.log, global, .{ .utf8 = "Framework is missing required files!" });
    };

    errdefer dev.route_lookup.clearAndFree(alloc);
    errdefer dev.client_graph.deinit();
    errdefer dev.server_graph.deinit();

    dev.configuration_hash_key = hash_key: {
        var hash = std.hash.Wyhash.init(128);

        if (bun.Environment.isDebug) {
            const stat = bun.sys.stat(bun.selfExePath() catch |e|
                Output.panic("unhandled {}", .{e})).unwrap() catch |e|
                Output.panic("unhandled {}", .{e});
            bun.writeAnyToHasher(&hash, stat.mtime());
            hash.update(bake.getHmrRuntime(dev.vm.io, .client).code);
            hash.update(bake.getHmrRuntime(dev.vm.io, .server).code);
        } else {
            hash.update(bun.Environment.git_sha_short);
        }

        for (dev.framework.file_system_router_types) |fsr| {
            bun.writeAnyToHasher(&hash, fsr.allow_layouts);
            bun.writeAnyToHasher(&hash, fsr.ignore_underscores);
            hash.update(fsr.entry_server);
            hash.update(&.{0});
            hash.update(fsr.entry_client orelse "");
            hash.update(&.{0});
            hash.update(fsr.prefix);
            hash.update(&.{0});
            hash.update(fsr.root);
            hash.update(&.{0});
            for (fsr.extensions) |ext| {
                hash.update(ext);
                hash.update(&.{0});
            }
            hash.update(&.{0});
            for (fsr.ignore_dirs) |dir| {
                hash.update(dir);
                hash.update(&.{0});
            }
            hash.update(&.{0});
        }

        if (dev.framework.server_components) |sc| {
            bun.writeAnyToHasher(&hash, true);
            bun.writeAnyToHasher(&hash, sc.separate_ssr_graph);
            hash.update(sc.client_register_server_reference);
            hash.update(&.{0});
            hash.update(sc.server_register_client_reference);
            hash.update(&.{0});
            hash.update(sc.server_register_server_reference);
            hash.update(&.{0});
            hash.update(sc.server_runtime_import);
            hash.update(&.{0});
        } else {
            bun.writeAnyToHasher(&hash, false);
        }

        if (dev.framework.react_fast_refresh) |rfr| {
            bun.writeAnyToHasher(&hash, true);
            hash.update(rfr.import_source);
        } else {
            bun.writeAnyToHasher(&hash, false);
        }

        for (dev.framework.built_in_modules.keys(), dev.framework.built_in_modules.values()) |k, v| {
            hash.update(k);
            hash.update(&.{0});
            bun.writeAnyToHasher(&hash, std.meta.activeTag(v));
            hash.update(switch (v) {
                inline else => |data| data,
            });
            hash.update(&.{0});
        }
        hash.update(&.{0});

        break :hash_key std.fmt.bytesToHex(std.mem.asBytes(&hash.final()), .lower);
    };

    // Add react fast refresh if needed. This is the first file on the client side,
    // as it will be referred to by index.
    if (dev.framework.react_fast_refresh) |rfr| {
        assert(try dev.client_graph.insertStale(rfr.import_source, false) == IncrementalGraph(.client).react_refresh_index);
    }

    if (!dev.frontend_only) {
        try dev.initServerRuntime();
    }

    // Initialize FrameworkRouter
    dev.router = router: {
        var types = try std.ArrayListUnmanaged(FrameworkRouter.Type).initCapacity(alloc, options.framework.file_system_router_types.len);
        errdefer types.deinit(alloc);

        for (options.framework.file_system_router_types) |fsr| {
            const buf = bun.path_buffer_pool.get();
            defer bun.path_buffer_pool.put(buf);
            const joined_root = bun.path.joinAbsStringBuf(dev.root, buf, &.{fsr.root}, .auto);
            const entry = dev.server_transpiler.resolver.readDirInfoIgnoreError(joined_root) orelse
                continue;

            const server_file = try dev.server_graph.insertStaleExtra(fsr.entry_server, false, true);
            const route_index = types.items.len;

            try types.append(alloc, .{
                .abs_root = bun.strings.withoutTrailingSlash(entry.abs_path),
                .prefix = fsr.prefix,
                .ignore_underscores = fsr.ignore_underscores,
                .ignore_dirs = fsr.ignore_dirs,
                .extensions = fsr.extensions,
                .style = fsr.style,
                .allow_layouts = fsr.allow_layouts,
                .server_file = toOpaqueFileId(.server, server_file),
                .client_file = if (fsr.entry_client) |client|
                    toOpaqueFileId(.client, try dev.client_graph.insertStale(client, false)).toOptional()
                else
                    .none,
                .server_file_string = null,
            });

            try dev.route_lookup.put(alloc, server_file, .{
                .route_index = FrameworkRouter.Route.Index.init(@intCast(route_index)),
                .should_recurse_when_visiting = true,
            });
        }

        break :router try FrameworkRouter.initEmpty(dev.root, types.items, alloc);
    };

    // TODO: move scanning to be one tick after server startup. this way the
    // line saying the server is ready shows quicker, and route errors show up
    // after that line.
    try dev.scanInitialRoutes();

    if (bun.FeatureFlags.bake_debugging_features and dev.has_pre_crash_handler)
        try bun.crash_handler.appendPreCrashHandler(dev.vm.io, DevServer, dev, dumpStateDueToCrash);

    bun.assert(dev.magic == .valid);

    return dev;
}

pub fn deinit(dev: *DevServer) void {
    debug.log("deinit", .{});
    dev_server_deinit_count_for_testing +|= 1;

    const alloc = dev.allocator();
    useAllFields(DevServer, .{
        .allocation_scope = {}, // deinit at end
        .assume_perfect_incremental_bundling = {},
        .bundler_options = {},
        .bundles_since_last_error = {},
        .client_transpiler = {},
        .configuration_hash_key = {},
        .inspector_server_id = {},
        .deferred_request_pool = {},
        .emit_incremental_visualizer_events = {},
        .emit_memory_visualizer_events = {},
        .framework = {},
        .route_styles = {},
        .frontend_only = {},
        .generation = {},
        .plugin_state = {},
        .root = {},
        .server = {},
        .server_transpiler = {},
        .ssr_transpiler = {},
        .vm = {},

        .active_websocket_connections = {
            while (dev.active_websocket_connections.count() > 0) {
                var it = dev.active_websocket_connections.keyIterator();
                const socket = it.next().?.*;
                // close synchronously unlinks and destroys the socket.
                socket.underlying.?.close();
            }
            dev.active_websocket_connections.deinit(alloc);
        },

        .memory_visualizer_timer = if (dev.memory_visualizer_timer.state == .ACTIVE)
            dev.vm.timer.remove(&dev.memory_visualizer_timer),
        .graph_safety_lock = dev.graph_safety_lock.lock(),
        .bun_watcher = dev.bun_watcher.deinit(true),
        .dump_dir = if (bun.FeatureFlags.bake_debugging_features) if (dev.dump_dir) |*dir| dir.close(dev.vm.io),
        .log = dev.log.deinit(),
        .server_fetch_function_callback = if (dev.server_fetch_function_callback) |*callback| callback.deinit(),
        .server_register_update_callback = if (dev.server_register_update_callback) |*callback| callback.deinit(),
        .ensure_async_local_storage_callback = if (dev.ensure_async_local_storage_callback) |*callback| callback.deinit(),
        .bundle_new_route_callback = if (dev.bundle_new_route_callback) |*callback| callback.deinit(),
        .new_route_params_callback = if (dev.new_route_params_callback) |*callback| callback.deinit(),
        .has_pre_crash_handler = if (dev.has_pre_crash_handler)
            bun.crash_handler.removePreCrashHandler(dev.vm.io, dev),
        .router = {
            dev.router.deinit(alloc);
        },
        .route_bundles = {
            for (dev.route_bundles.items) |*rb| {
                rb.deinit(alloc);
            }
            dev.route_bundles.deinit(alloc);
        },
        .server_graph = dev.server_graph.deinit(),
        .client_graph = dev.client_graph.deinit(),
        .barrel_files_with_deferrals = {
            for (dev.barrel_files_with_deferrals.keys()) |key| {
                alloc.free(key);
            }
            dev.barrel_files_with_deferrals.deinit(alloc);
        },
        .barrel_needed_exports = {
            var it = dev.barrel_needed_exports.iterator();
            while (it.next()) |entry| {
                var inner = entry.value_ptr.*;
                var inner_it = inner.keyIterator();
                while (inner_it.next()) |k| alloc.free(k.*);
                inner.deinit(alloc);
                alloc.free(entry.key_ptr.*);
            }
            dev.barrel_needed_exports.deinit(alloc);
        },
        .assets = dev.assets.deinit(alloc),
        .incremental_result = useAllFields(IncrementalResult, .{
            .had_adjusted_edges = {},
            .client_components_added = dev.incremental_result.client_components_added.deinit(alloc),
            .framework_routes_affected = dev.incremental_result.framework_routes_affected.deinit(alloc),
            .client_components_removed = dev.incremental_result.client_components_removed.deinit(alloc),
            .failures_removed = {
                for (dev.incremental_result.failures_removed.items) |failure| failure.deinit(alloc);
                dev.incremental_result.failures_removed.deinit(alloc);
            },
            .client_components_affected = dev.incremental_result.client_components_affected.deinit(alloc),
            .failures_added = dev.incremental_result.failures_added.deinit(alloc),
            .html_routes_soft_affected = dev.incremental_result.html_routes_soft_affected.deinit(alloc),
            .html_routes_hard_affected = dev.incremental_result.html_routes_hard_affected.deinit(alloc),
        }),
        .has_tailwind_plugin_hack = if (dev.has_tailwind_plugin_hack) |*hack| {
            for (hack.keys()) |key| {
                alloc.free(key);
            }
            hack.deinit(alloc);
        },
        .directory_watchers = {
            // dev.directory_watchers.dependencies
            for (dev.directory_watchers.watches.keys()) |dir_name| {
                alloc.free(dir_name);
            }
            for (dev.directory_watchers.dependencies.items) |watcher| {
                alloc.free(watcher.specifier);
            }
            dev.directory_watchers.watches.deinit(alloc);
            dev.directory_watchers.dependencies.deinit(alloc);
            dev.directory_watchers.dependencies_free_list.deinit(alloc);
        },
        .html_router = dev.html_router.map.deinit(alloc),
        .bundling_failures = {
            for (dev.bundling_failures.keys()) |failure| {
                failure.deinit(alloc);
            }
            dev.bundling_failures.deinit(alloc);
        },
        .current_bundle = {
            if (dev.current_bundle) |_| {
                bun.debugAssert(false); // impossible to de-initialize this state correctly.
            }
        },
        .next_bundle = {
            var requests = dev.next_bundle.requests.iterator();
            while (requests.next()) |request| {
                // TODO: deinitializing in this state is almost certainly an assertion failure.
                // This code is shipped in release because it is only reachable by experimental server components.
                bun.debugAssert(request.handler != .server_handler);
                request.deref();
            }
            dev.next_bundle.route_queue.deinit(alloc);
            dev.next_bundle.promise.deinitIdempotently();
        },
        .route_lookup = dev.route_lookup.deinit(alloc),
        .source_maps = {
            for (dev.source_maps.entries.values()) |*value| {
                bun.assert(value.ref_count > 0);
                value.ref_count = 0;
                value.deinit();
            }
            dev.source_maps.entries.deinit(alloc);

            if (dev.source_maps.weak_ref_sweep_timer.state == .ACTIVE)
                dev.vm.timer.remove(&dev.source_maps.weak_ref_sweep_timer);
        },

        .watcher_atomics = for (&dev.watcher_atomics.events) |*event| {
            event.dirs.deinit(dev.allocator());
            event.files.deinit(dev.allocator());
            event.extra_files.deinit(dev.allocator());
        },
        .hot_reload_task = {},
        .testing_batch_events = switch (dev.testing_batch_events) {
            .disabled => {},
            .enabled => |*batch| {
                batch.entry_points.deinit(alloc);
            },
            .enable_after_bundle => {},
        },
        .broadcast_console_log_from_browser_to_server = {},

        .magic = {
            bun.debugAssert(dev.magic == .valid);
            dev.magic = undefined;
        },
    });
    if (comptime AllocationScope.enabled) {
        dev.allocation_scope.deinit();
    }
    bun.destroy(dev);
}

