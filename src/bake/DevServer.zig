const RequestEnsureRouteBundledCtx = struct {
    dev: *DevServer,
    req: ReqOrSaved,
    resp: AnyResponse,
    kind: DeferredRequest.Handler.Kind,
    route_bundle_index: RouteBundle.Index,

    fn onDefer(this: *RequestEnsureRouteBundledCtx, bundle_field: BundleQueueType) bun.JSError!void {
        const requests_array: *DeferredRequest.List = switch (bundle_field) {
            .current_bundle => &this.dev.current_bundle.?.requests,
            .next_bundle => &this.dev.next_bundle.requests,
        };
        try this.dev.deferRequest(requests_array, this.route_bundle_index, this.kind, this.req, this.resp);
    }

    fn onLoaded(this: *RequestEnsureRouteBundledCtx) bun.JSError!void {
        switch (this.kind) {
            .server_handler => try this.dev.onFrameworkRequestWithBundle(
                this.route_bundle_index,
                if (this.req == .req) .{ .stack = this.req.req } else .{ .saved = this.req.saved },
                this.resp,
            ),
            .bundled_html_page => this.dev.onHtmlRequestWithBundle(
                this.route_bundle_index,
                this.resp,
                this.req.method(),
            ),
        }
    }

    fn onFailure(this: *RequestEnsureRouteBundledCtx) bun.JSError!void {
        try this.dev.sendSerializedFailures(
            .{ .http = this.resp },
            (&(this.dev.routeBundlePtr(this.route_bundle_index).data.framework.evaluate_failure.?))[0..1],
            .evaluation,
            null,
        );
    }

    fn onPluginError(this: *RequestEnsureRouteBundledCtx) bun.JSError!void {
        this.resp.end("Plugin Error", false) catch |err| closeResponseAfterWriteFailure(this.resp, err);
    }

    fn toDevResponse(this: *RequestEnsureRouteBundledCtx) bun.JSError!DevResponse {
        return .{ .http = this.resp };
    }
};

const BundleQueueType = enum { next_bundle, current_bundle };

fn ensureRouteIsBundled(
    dev: *DevServer,
    route_bundle_index: RouteBundle.Index,
    comptime Ctx: type,
    ctx: *Ctx,
) bun.JSError!void {
    const defer_function: *const fn (*Ctx, BundleQueueType) bun.JSError!void = @field(Ctx, "onDefer");
    const on_loaded_function: *const fn (*Ctx) bun.JSError!void = @field(Ctx, "onLoaded");
    const on_failure_function: *const fn (*Ctx) bun.JSError!void = @field(Ctx, "onFailure");
    const on_plugin_error: *const fn (*Ctx) bun.JSError!void = @field(Ctx, "onPluginError");
    const to_dev_response: *const fn (*Ctx) bun.JSError!DevResponse = @field(Ctx, "toDevResponse");

    assert(dev.magic == .valid);
    assert(dev.server != null);
    const state = dev.routeBundlePtr(route_bundle_index).server_state;
    sw: switch (state) {
        .unqueued => {
            // We already are bundling something, defer the request
            if (dev.current_bundle != null) {
                try dev.next_bundle.route_queue.put(dev.allocator(), route_bundle_index, {});
                try defer_function(ctx, .next_bundle);
                dev.routeBundlePtr(route_bundle_index).server_state = .deferred_to_next_bundle;
                return;
            }

            // No current bundle, we'll create a bundle with just this route, but first:
            // If plugins are not yet loaded, prepare them.
            // In the case plugins are set to &.{}, this will not hit `.pending`.
            plugin: switch (dev.plugin_state) {
                .unknown => if (dev.bundler_options.plugin != null) {
                    // Framework-provided plugin is likely going to be phased out later
                    dev.plugin_state = .loaded;
                } else {
                    // TODO: implement a proper solution here
                    dev.has_tailwind_plugin_hack = if (dev.vm.transpiler.options.serve_plugins) |serve_plugins|
                        for (serve_plugins) |plugin| {
                            if (bun.strings.includes(plugin, "tailwind")) break .empty;
                        } else null
                    else
                        null;

                    switch (dev.server.?.getOrLoadPlugins(.{ .dev_server = dev })) {
                        .pending => {
                            dev.plugin_state = .pending;
                            continue :plugin .pending;
                        },
                        .err => {
                            dev.plugin_state = .err;
                            continue :plugin .err;
                        },
                        .ready => |ready| {
                            dev.plugin_state = .loaded;
                            dev.bundler_options.plugin = ready;
                        },
                    }
                },
                .pending => {
                    try dev.next_bundle.route_queue.put(dev.allocator(), route_bundle_index, {});
                    // try dev.deferRequest(&dev.next_bundle.requests, route_bundle_index, kind, req, resp);
                    try defer_function(ctx, .next_bundle);
                    dev.routeBundlePtr(route_bundle_index).server_state = .deferred_to_next_bundle;
                    return;
                },
                .err => {
                    // TODO: render plugin error page
                    // if (resp) |r| r.end("Plugin Error", false);
                    try on_plugin_error(ctx);
                    return;
                },
                .loaded => {},
            }

            // Prepare a bundle with just this route.
            var sfa_buffer: [4096]u8 = undefined;
            var sfa: std.heap.BufferFirstAllocator = .init(&sfa_buffer, dev.allocator());
            const temp_alloc = sfa.allocator();

            var entry_points: EntryPointList = .empty;
            defer entry_points.deinit(temp_alloc);
            try dev.appendRouteEntryPointsIfNotStale(&entry_points, temp_alloc, route_bundle_index);

            // If all files were already bundled (possible with layouts),
            // then no entry points will be queued up here. That does
            // not mean the route is ready for presentation.
            if (entry_points.set.count() == 0) {
                if (dev.bundling_failures.count() > 0) {
                    dev.routeBundlePtr(route_bundle_index).server_state = .possible_bundling_failures;
                    continue :sw .possible_bundling_failures;
                } else {
                    dev.routeBundlePtr(route_bundle_index).server_state = .loaded;
                    continue :sw .loaded;
                }
            }

            try dev.next_bundle.route_queue.put(dev.allocator(), route_bundle_index, {});
            try defer_function(ctx, .next_bundle);
            dev.routeBundlePtr(route_bundle_index).server_state = .bundling;

            dev.startAsyncBundle(
                entry_points,
                false,
                bun.SystemTimer.start() catch @panic("timers unsupported"),
            ) catch |err| switch (@as(anyerror, err)) {
                error.OutOfMemory => return error.OutOfMemory,
                error.JSError => return error.JSError,
                else => return dev.vm.global.throw("Failed to start bundler: {s}", .{@errorName(err)}),
            };
        },
        .deferred_to_next_bundle => {
            bun.assert(dev.next_bundle.route_queue.get(route_bundle_index) != null);
            try defer_function(ctx, .next_bundle);
        },
        .bundling => {
            bun.assert(dev.current_bundle != null);
            try defer_function(ctx, .current_bundle);
        },
        .possible_bundling_failures => {
            if (dev.bundling_failures.count() > 0) {
                // Trace the graph to see if there are any failures that are
                // reachable by this route.
                switch (try checkRouteFailures(dev, route_bundle_index, try to_dev_response(ctx))) {
                    .stop => return,
                    .ok => {}, // Errors were cleared or not in the way.
                    .rebuild => continue :sw .unqueued, // Do the build all over again
                }
            }

            dev.routeBundlePtr(route_bundle_index).server_state = .loaded;
            continue :sw .loaded;
        },
        .evaluation_failure => {
            try on_failure_function(ctx);
        },
        .loaded => try on_loaded_function(ctx),
    }
}

const ReqOrSaved = union(enum) {
    req: *Request,
    saved: bun.jsc.API.SavedRequest,

    pub fn method(this: *const @This()) bun.http.Method {
        return switch (this.*) {
            .req => |req| bun.http.Method.which(req.method()) orelse .POST,
            .saved => |saved| saved.request.method,
        };
    }
};

fn deferRequest(
    dev: *DevServer,
    requests_array: *DeferredRequest.List,
    route_bundle_index: RouteBundle.Index,
    kind: DeferredRequest.Handler.Kind,
    req: ReqOrSaved,
    resp: AnyResponse,
) !void {
    const deferred = dev.deferred_request_pool.get();
    debug.log("DeferredRequest(0x{x}).init", .{@intFromPtr(deferred)});

    const method = switch (req) {
        .req => |r| bun.http.Method.which(r.method()) orelse .GET,
        .saved => |saved| saved.request.method,
    };

    deferred.* = .{
        .route_bundle_index = route_bundle_index,
        .dev = dev,
        .handler = switch (kind) {
            .bundled_html_page => brk: {
                resp.onAborted(*DeferredRequest, DeferredRequest.onAbort, deferred);
                break :brk .{ .bundled_html_page = .{ .response = resp, .method = method } };
            },
            .server_handler => brk: {
                const server_handler = switch (req) {
                    .req => |r| (try dev.server.?.prepareAndSaveJsRequestContext(r, resp, method)) orelse {
                        dev.deferred_request_pool.put(deferred);
                        return;
                    },
                    .saved => |saved| saved,
                };
                server_handler.ctx.ref();
                server_handler.ctx.setAdditionalOnAbortCallback(.{
                    .cb = DeferredRequest.onAbortWrapper,
                    .data = .init(deferred),
                    .deref_fn = struct {
                        fn deref_fn(ptr: bun.bindgen.NativeCallbackContext(.vm)) void {
                            const self = ptr.get(*DeferredRequest);
                            self.weakDeref();
                        }
                    }.deref_fn,
                });
                break :brk .{
                    .server_handler = server_handler,
                };
            },
        },
    };

    if (deferred.handler == .server_handler) {
        deferred.weakRef();
    }

    requests_array.prepend(deferred);
}

fn checkRouteFailures(
    dev: *DevServer,
    route_bundle_index: RouteBundle.Index,
    resp: DevResponse,
) !enum { stop, ok, rebuild } {
    var sfa_state_buffer: [65536]u8 = undefined;
    var sfa_state: std.heap.BufferFirstAllocator = .init(&sfa_state_buffer, dev.allocator());
    const sfa = sfa_state.allocator();
    var gts = try dev.initGraphTraceState(sfa, 0);
    defer gts.deinit(sfa);
    dev.graph_safety_lock.lock();
    defer dev.graph_safety_lock.unlock();
    try dev.traceAllRouteImports(dev.routeBundlePtr(route_bundle_index), &gts, .find_errors);
    if (gts.failed_files.items.len > 0) {
        if (!dev.assume_perfect_incremental_bundling) {
            // Cache bust EVERYTHING reachable
            inline for (.{
                .{ .graph = &dev.client_graph, .bits = &gts.client_bits },
                .{ .graph = &dev.server_graph, .bits = &gts.server_bits },
            }) |entry| {
                var it = entry.bits.iterator(.{});
                while (it.next()) |file_index| {
                    entry.graph.markStale(.init(@intCast(file_index)));
                }
            }
            return .rebuild;
        }

        const failures = try sfa.alloc(SerializedFailure, gts.failed_files.items.len);
        defer sfa.free(failures);
        for (gts.failed_files.items, failures) |failed, *failure| {
            const owner: SerializedFailure.Owner = switch (failed) {
                .client => |index| .{ .client = index },
                .server => |index| .{ .server = index },
            };
            failure.* = dev.bundling_failures.getKeyAdapted(owner, SerializedFailure.ArrayHashAdapter{}) orelse
                @panic("failed graph file has no diagnostic");
        }
        try dev.sendSerializedFailures(
            resp,
            failures,
            .bundler,
            null,
        );
        return .stop;
    } else {
        // Failures are unreachable by this route, so it is OK to load.
        return .ok;
    }
}

fn appendRouteEntryPointsIfNotStale(dev: *DevServer, entry_points: *EntryPointList, alloc: Allocator, rbi: RouteBundle.Index) bun.OOM!void {
    const server_file_names = dev.server_graph.bundled_files.keys();
    const client_file_names = dev.client_graph.bundled_files.keys();

    // Build a list of all files that have not yet been bundled.
    switch (dev.routeBundlePtr(rbi).data) {
        .framework => |*bundle| {
            var route = dev.router.routePtr(bundle.route_index);
            const router_type = dev.router.typePtr(route.type);
            try dev.appendOpaqueEntryPoint(server_file_names, entry_points, alloc, .server, router_type.server_file);
            try dev.appendOpaqueEntryPoint(client_file_names, entry_points, alloc, .client, router_type.client_file);
            try dev.appendOpaqueEntryPoint(server_file_names, entry_points, alloc, .server, route.file_page);
            try dev.appendOpaqueEntryPoint(server_file_names, entry_points, alloc, .server, route.file_layout);
            while (route.parent.unwrap()) |parent_index| {
                route = dev.router.routePtr(parent_index);
                try dev.appendOpaqueEntryPoint(server_file_names, entry_points, alloc, .server, route.file_layout);
            }
        },
        .html => |*html| {
            try entry_points.append(alloc, html.html_bundle.data.bundle.data.path.slice(), .{ .client = true });
        },
    }

    if (dev.has_tailwind_plugin_hack) |*map| {
        for (map.keys()) |abs_path| {
            const file = (dev.client_graph.bundled_files.get(abs_path) orelse continue).unpack();
            if (file.kind() == .css)
                bun.handleOom(entry_points.appendCss(alloc, abs_path));
        }
    }
}

fn computeArgumentsForFrameworkRequest(
    dev: *DevServer,
    route_bundle_index: RouteBundle.Index,
    framework_bundle: *RouteBundle.Framework,
    params: *const FrameworkRouter.MatchedParams,
) bun.JSError!FrameworkRequestOwnedMetadata {
    const route_bundle = dev.routeBundlePtr(route_bundle_index);
    const router_type = dev.router.typePtr(dev.router.routePtr(framework_bundle.route_index).type);
    const alloc = dev.allocator();

    const server_file_string = router_type.server_file_string orelse str: {
        const name = dev.server_graph.bundled_files.keys()[fromOpaqueFileId(.server, router_type.server_file).get()];
        const relative_path = try dev.relativePath(alloc, name);
        defer alloc.free(relative_path);
        const value = bun.String.cloneUTF8(relative_path);
        router_type.server_file_string = value;
        break :str value;
    };
    var router_type_main = try bun.bindgen.DOMString.fromBunString(server_file_string.dupeRef());
    errdefer router_type_main.deinit();

    const module_list = framework_bundle.cached_module_list orelse list: {
        const value = try dev.generateFrameworkModuleList(framework_bundle);
        framework_bundle.cached_module_list = value;
        break :list value;
    };
    var route_modules = try @FieldType(FrameworkRequestOwnedMetadata, "routeModules").fromBunStrings(module_list);
    errdefer route_modules.deinit();

    const client_bundle_url = framework_bundle.cached_client_bundle_url orelse url: {
        const bundle_index: u32 = route_bundle_index.get();
        const generation: u32 = route_bundle.client_script_generation;
        const value = try bun.String.createFormat(client_prefix ++ "/route-{x}{x}.js", .{
            std.mem.asBytes(&bundle_index),
            std.mem.asBytes(&generation),
        });
        framework_bundle.cached_client_bundle_url = value;
        break :url value;
    };
    var client_entry_url = try bun.bindgen.DOMString.fromBunString(client_bundle_url.dupeRef());
    errdefer client_entry_url.deinit();

    const css_files = framework_bundle.cached_css_files orelse list: {
        const value = try dev.generateCssStringList(route_bundle);
        framework_bundle.cached_css_files = value;
        break :list value;
    };
    var styles = try @FieldType(FrameworkRequestOwnedMetadata, "styles").fromBunStrings(css_files);
    errdefer styles.deinit();

    const Params = @FieldType(FrameworkRequestOwnedMetadata, "params");
    const ParamsRecord = @typeInfo(Params).optional.child;
    var route_params: Params = if (params.len == 0) null else try bake.FrameworkRouterEngine.matchedParamsToRecord(params, ParamsRecord);
    errdefer if (route_params) |*values| values.deinit();

    return .{
        .routerTypeMain = router_type_main,
        .routeModules = route_modules,
        .clientEntryUrl = client_entry_url,
        .styles = styles,
        .params = route_params,
    };
}

fn generateFrameworkModuleList(dev: *DevServer, framework_bundle: *const RouteBundle.Framework) bun.OOM![]bun.String {
    const alloc = dev.allocator();
    const keys = dev.server_graph.bundled_files.keys();
    var count: usize = 1;
    var route = dev.router.routePtr(framework_bundle.route_index);
    while (true) {
        if (route.file_layout != .none) count += 1;
        route = dev.router.routePtr(route.parent.unwrap() orelse break);
    }

    const modules = try alloc.alloc(bun.String, count);
    var initialized: usize = 0;
    errdefer {
        for (modules[0..initialized]) |module| module.deref();
        alloc.free(modules);
    }

    route = dev.router.routePtr(framework_bundle.route_index);
    const page_path = try dev.relativePath(alloc, keys[fromOpaqueFileId(.server, route.file_page.unwrap().?).get()]);
    defer alloc.free(page_path);
    modules[0] = bun.String.cloneUTF8(page_path);
    initialized = 1;

    while (true) {
        if (route.file_layout.unwrap()) |layout| {
            const relative_path = try dev.relativePath(alloc, keys[fromOpaqueFileId(.server, layout).get()]);
            defer alloc.free(relative_path);
            modules[initialized] = bun.String.cloneUTF8(relative_path);
            initialized += 1;
        }
        route = dev.router.routePtr(route.parent.unwrap() orelse break);
    }
    return modules;
}

