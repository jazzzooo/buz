const b = @import("bindgen_schema");

fn code(comptime name: []const u8, comptime class: b.ErrorClass) b.DomainError {
    return named(name, class, null);
}

fn named(comptime name: []const u8, comptime class: b.ErrorClass, comptime error_name: ?[]const u8) b.DomainError {
    return b.domainError(name, b.dom_string, .{
        .class = class,
        .code = name,
        .name_override = error_name,
        .message = .payload,
    });
}

fn variant(comptime name: []const u8, comptime class: b.ErrorClass) b.DomainError {
    const suffix = switch (class) {
        .generic_error => "Error",
        .type_error => "TypeError",
        .range_error => "RangeError",
        .syntax_error => "SyntaxError",
        .uri_error => "URIError",
    };
    return b.domainError(name ++ "_" ++ suffix, b.dom_string, .{
        .class = class,
        .code = name,
        .message = .payload,
    });
}

