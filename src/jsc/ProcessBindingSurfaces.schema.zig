const configurable = b.SurfaceMemberOptions{ .attributes = .{} };

fn stubFunction(comptime group: []const u8, comptime name: []const u8) b.SurfaceMember {
    return b.surfaceFunction(name, stubs.schema.function(group ++ "_" ++ name), configurable);
}

fn cppLazy(comptime name: []const u8, comptime symbol: []const u8) b.SurfaceMember {
    return b.surfaceLazyProperty(name, stubs.schema.function(symbol), configurable);
}

