fn nativeMember(comptime name: []const u8) b.SurfaceMember {
    if (std.mem.eql(u8, name, "configs")) return b.surfaceUndefined(name, configurable);
    return b.surfaceString(name, native_source, configurable);
}

fn nativeMembers() [module_names.len]b.SurfaceMember {
    @setEvalBranchQuota(100_000);
    var members: [module_names.len]b.SurfaceMember = undefined;
    inline for (module_names, 0..) |name, index| members[index] = nativeMember(name);
    return members;
}

const natives = b.objectSurface("ProcessBindingNatives", nativeMembers(), .{});

pub const schema = b.moduleWithSurfaces("ProcessBindingNativesSurface", .{natives});
